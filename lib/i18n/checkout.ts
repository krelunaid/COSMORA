export function checkoutErrorText(locale: Locale, reason: string | Error): string {
  if (reason instanceof AccountRequestError) {
    if (reason.status === 401) return checkoutText(locale, 'loginRequired');
    if (reason.code === 'CHECKOUT_ATTEMPT_TERMINAL') return checkoutText(locale, 'checkOrders');
    if (reason.code === 'CHECKOUT_UNAVAILABLE') return checkoutText(locale, 'checkoutReserved');
    if (reason.code === 'CHECKOUT_RECOVERY_REQUIRED') return checkoutText(locale, 'checkoutRecovery');
    if (reason.code === 'CHECKOUT_AWAITING_RESULT') return checkoutText(locale, 'checkoutAwaitingResult');
    if (reason.code === 'ORDER_VERIFICATION_UNAVAILABLE') return checkoutText(locale, 'verifyError');
    if (reason.code === 'ORDER_ACTION_DISPUTED') return checkoutText(locale, 'disputeOpen');
    const key = reason.code && refundErrorKeys[reason.code];
    if (key) return checkoutText(locale, key);
  }
  const message = reason instanceof Error ? reason.message : reason;
  const key = message.startsWith('Accedi')
    ? 'loginRequired'
    : (checkoutErrorKeys[message] ?? 'error');
  return checkoutText(locale, key);
}
