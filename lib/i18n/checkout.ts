export type CheckoutKey = keyof typeof checkoutCopy;
const index: Record<Locale, number> = { it: 0, en: 1, fr: 2, de: 3, es: 4 };
export const checkoutText = (locale: Locale, key: CheckoutKey): string =>
  checkoutCopy[key][index[locale]];

