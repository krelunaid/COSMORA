export function communityText(locale: Locale, text: string): string {
  return translations[text]?.[locale] ?? text;
}

const translators = Object.fromEntries(
  (['it', 'en', 'fr', 'de', 'es'] as const).map((locale) => [
    locale,
    (text: string) => communityText(locale, text),
  ]),
) as Record<Locale, (text: string) => string>;

export function communityTranslator(locale: Locale) {
  return translators[locale];
}

export function communityError(
  locale: Locale,
  error: unknown,
  fallback = 'Operazione non riuscita.',
): string {
  const message =
    error instanceof Error
      ? error.message
      : typeof error === 'string'
        ? error
        : '';
  if (translations[message]) return translations[message][locale];
  if (/^(Accedi |Authentication required)/.test(message))
    return communityText(locale, 'Accedi per continuare.');
  return communityText(locale, fallback);
}
